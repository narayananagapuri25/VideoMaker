export type AspectRatio = "9:16" | "16:9";
export type Language = "Hinglish" | "Hindi" | "English" | "Telugu";
export type VisualProvider = "adobe-firefly" | "pexels" | "other";

export type SceneVisualLayout =
  | "hero"
  | "illustration"
  | "chart"
  | "candlestick"
  | "dashboard"
  | "process"
  | "comparison"
  | "timeline"
  | "diagram"
  | "infographic";

export interface SceneVisualPlan {
  layout: SceneVisualLayout;
  subject: string;
  headline?: string;
  labels?: string[];
  steps?: string[];
  /** Normalised illustrative values (0–100), never real market prices or factual measurements. */
  values?: number[];
  trend?: "up" | "down" | "volatile" | "flat";
  note?: string;
}

export interface Scene {
  id: string;
  title: string;
  narration: string;
  caption: string;
  visualPrompt: string;
  /** AI art-direction instructions used by both the live preview and MP4 renderer. */
  visualPlan?: SceneVisualPlan;
  duration: number;
  imageDataUrl?: string;
  /** True when generated by an integrated AI provider, not imported by the user. */
  imageGeneratedByAI?: boolean;
  imageProvider?: VisualProvider;
  imageSourceNote?: string;
  imageCommercialUseConfirmed?: boolean;
  videoClipSource?: "pixabay" | "local";
  videoClipId?: number;
  videoClipName?: string;
  videoClipAuthor?: string;
  videoClipPageUrl?: string;
  videoClipDuration?: number;
  videoClipStart?: number;
  videoDataUrl?: string;
  /** True when the clip was generated by the integrated AI video provider, not imported. */
  videoGeneratedByAI?: boolean;
  videoSourceNote?: string;
  videoCommercialUseConfirmed?: boolean;
}

export interface StudioProject {
  id: string;
  title: string;
  topic: string;
  language: Language;
  aspectRatio: AspectRatio;
  targetDuration: number;
  script: string;
  scenes: Scene[];
  /** Last topic and script used to build this storyboard; stale drafts cannot be exported. */
  storyboardSourceTopic?: string;
  storyboardSourceScript?: string;
  storyboardSourceTargetDuration?: number;
  storyboardSourceAspectRatio?: AspectRatio;
  /** Language used when the current storyboard was generated or last rebuilt. */
  storyboardSourceLanguage?: Language;
  /** Research/editorial caveat shown in the editor, never included in narration. */
  editorialNote?: string;
  voiceAudioDataUrl?: string;
  voiceAudioName?: string;
  updatedAt: number;
}

export interface GeneratedStory {
  title: string;
  script: string;
  scenes: Array<Omit<Scene, "id">>;
  editorialNote?: string;
}